#!/usr/bin/env node
// THE SIGNED ANSWER, CHECKED AGAINST THE RELAY'S OWN VECTOR.
//
// The outer frame and the inner OrderQuote are signed by different keys. This check verifies both, the request
// correlation, the fee arithmetic, the context and the view points, then breaks one field at a time.
//
// Run: node tools/check-relay-answer.mjs
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { keccak256, secp256k1 } from "../src/primitives.mjs";
import { relayQuoteDigest, verifyFirmAnswer, verifyRelayQuoteFrame } from "../src/relayQuote.mjs";
import { verifyCounterparty } from "../src/order.mjs";
import { xmrAmountVerdict } from "../src/xmrAmountPolicy.mjs";
import { buildRelayAnswerFixture } from "./gen-relay-answer.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const fixturePath = join(here, "fixtures", "relay-answer.json");
const seedPath = join(here, "fixtures", "relay-answer.seed.json");
const fixture = JSON.parse(readFileSync(fixturePath, "utf8"));
const answer = fixture.answer;
const quoteKey = (() => {
  const privateKey = String(fixture.keys.quote).replace(/^0x/, "");
  const publicKey = secp256k1.Point.BASE.multiply(BigInt("0x" + privateKey)).toBytes(false);
  return "0x" + Buffer.from(keccak256(publicKey.slice(1)).slice(12)).toString("hex");
})();
const request = {
  terms: fixture.request.terms,
  edViewPointClient: fixture.request.edViewPointClient,
  edViewPointNode: fixture.request.edViewPointNode,
};
const features = { quoteKey, relayId: answer.relayId };

let pass = 0;
const fails = [];
const ok = (message) => { pass += 1; console.log("  ok    " + message); };
const bad = (message) => { fails.push(message); console.log("  FAIL  " + message); };
const hex = (bytes) => "0x" + Buffer.from(bytes).toString("hex");

console.log("=== 0) THE COMMITTED VECTOR IS REPRODUCIBLE ===");
const committed = readFileSync(fixturePath, "utf8").replace(/\r\n/g, "\n");
if (buildRelayAnswerFixture() === committed) {
  ok("the generator reproduces the committed fixture byte for byte");
} else {
  bad("the fixture is stale; run node tools/gen-relay-answer.mjs --write");
}
{
  // THE SEED IS THE INPUT, NOT THE FIXTURE. A changed order amount must change the generated bytes; otherwise the
  // generator is still copying the answer it is supposed to derive.
  const seed = JSON.parse(readFileSync(seedPath, "utf8"));
  const changedSeed = JSON.parse(JSON.stringify(seed));
  changedSeed.terms.order.amount = (BigInt(changedSeed.terms.order.amount) + 1n).toString();
  if (buildRelayAnswerFixture({ seed: changedSeed }) !== committed) {
    ok("a changed seed field changes the generated fixture");
  } else {
    bad("a changed seed field reproduced the committed fixture");
  }
}

console.log("=== 1) THE OUTER FRAME MATCHES THE VECTOR ===");
if (hex(relayQuoteDigest(answer)) === fixture.answerExpected.digest) ok("the outer digest matches the relay vector");
else bad("outer digest: " + hex(relayQuoteDigest(answer)));
try {
  verifyRelayQuoteFrame(answer, quoteKey);
  ok("the outer signature recovers the quote key");
} catch (error) { bad("outer signature: " + JSON.stringify(error && (error.code || error.message))); }

console.log("=== 2) THE ANSWER BINDS THE REQUEST ===");
try {
  const verified = verifyFirmAnswer({ answer, features, request, now: fixture.now });
  if (verified.quote.xmrAmount === fixture.request.terms.xmrAmount
    && verified.orderQuote.quoteSignature === JSON.parse(answer.payload).quoteSignature) {
    ok("the inner quote is bound to the terms and its signature");
  } else bad("verified quote: " + JSON.stringify(verified.quote));
} catch (error) { bad("valid answer refused: " + JSON.stringify(error && (error.code || error.params || error.message))); }

console.log("=== 2b) A BETTER XMR AMOUNT IS ACCEPTED, A WORSE ONE IS REFUSED ===");
{
  const withXmr = (xmrAmount) => ({
    ...request,
    terms: { ...request.terms, xmrAmount },
  });
  const better = verifyFirmAnswer({
    answer, features, now: fixture.now,
    request: withXmr("999999999999"),
  });
  if (better && better.quote.xmrAmount === fixture.request.terms.xmrAmount) ok("an ask accepts a signed amount above the request");
  else bad("an ask refused a better signed amount");
  try {
    verifyFirmAnswer({ answer, features, now: fixture.now, request: withXmr("1000000000001") });
    bad("an ask accepted a signed amount below the request");
  } catch (error) {
    if (error && error.code === "quote-refused" && error.params && error.params.field === "xmrAmount") ok("an ask refuses a signed amount below the request");
    else bad("an ask refused a worse amount with " + JSON.stringify(error && (error.code || error.params || error.message)));
  }
  const cases = [
    ["ask equal", "ask", "1000000000000", "1000000000000", true],
    ["ask better", "ask", "1000000000000", "1000000000001", true],
    ["ask worse", "ask", "1000000000001", "1000000000000", false],
    ["bid equal", "bid", "1000000000000", "1000000000000", true],
    ["bid better", "bid", "1000000000001", "1000000000000", true],
    ["bid worse", "bid", "1000000000000", "1000000000001", false],
    ["unreadable", "ask", "not-a-number", "1000000000000", false],
    ["unknown side", "sideways", "1000000000000", "1000000000000", false],
  ];
  for (const [label, side, requested, signed, want] of cases) {
    const got = xmrAmountVerdict({ side, requested, signed }).ok;
    if (got === want) ok(`${label}: ${got ? "accepted" : "refused"}`);
    else bad(`${label}: got ${got}, expected ${want}`);
  }
}

console.log("=== 3) EACH SIDE CARRIES A REAL KNOWLEDGE PROOF ===");
const proofSide = (half) => ({
  pub: { ed: half.edPoint },
  commitHalfClaimer: half.commitHalf,
  proof: half.proof,
});
for (const [label, half] of [["client", fixture.request.clientHalf], ["node", JSON.parse(answer.payload).nodeHalf]]) {
  try {
    verifyCounterparty({ side: proofSide(half), order: fixture.request.terms.order });
    ok(`the ${label} side proves knowledge of one half in this order context`);
  } catch (error) {
    bad(`${label} proof: ` + JSON.stringify(error && (error.code || error.message)));
  }
}
for (const field of ["pokA", "pokB"]) {
  const brokenProof = JSON.parse(JSON.stringify(proofSide(JSON.parse(answer.payload).nodeHalf)));
  brokenProof.proof[field] = "0x" + "00".repeat(64);
  try {
    verifyCounterparty({ side: brokenProof, order: fixture.request.terms.order });
    bad(`a broken ${field} passed`);
  } catch {
    ok(`a broken ${field} is refused`);
  }
}

console.log("=== 4) A CHANGED FIELD IS REFUSED ===");
for (const [label, change] of [
  ["a changed provider", { provider: "0x" + "01".repeat(20) }],
  ["a changed signature", { signature: "0x" + "00".repeat(65) }],
  ["a changed payload", { payload: answer.payload + " " }],
]) {
  try { verifyRelayQuoteFrame({ ...answer, ...change }, quoteKey); bad(label + " passed the outer check"); }
  catch { ok(label + " is refused by the outer signature"); }
}
const changedQuote = JSON.parse(answer.payload);
changedQuote.quote.amount = "1";
try {
  verifyFirmAnswer({ answer: { ...answer, payload: JSON.stringify(changedQuote) }, features, request, now: fixture.now });
  bad("a changed inner amount passed");
} catch { ok("a changed inner amount is refused"); }
const changedContext = JSON.parse(answer.payload);
changedContext.context = "other";
try {
  verifyFirmAnswer({ answer: { ...answer, payload: JSON.stringify(changedContext) }, features, request, now: fixture.now });
  bad("a changed context passed");
} catch { ok("a changed context is refused"); }

console.log("");
console.log(fails.length ? "FAILED: " + fails.length + " (passed " + pass + ")" : "relay answer: " + pass + " checks passed.");
if (fails.length) process.exit(1);
