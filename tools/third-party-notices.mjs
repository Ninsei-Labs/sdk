#!/usr/bin/env node
// THIRD-PARTY NOTICES FOR THE PRODUCTION TREE.
//
// MIT, ISC, BSD and Apache-2.0 dependencies keep their own copyright notices and licence texts. The allowlist says
// which licences we accept; this file carries the texts themselves into the published package, so a consumer
// receives every notice with the SDK instead of having to reconstruct it from a lock file.
//
// The output is deterministic: packages sorted by name and version, licence files sorted by name, line endings
// normalised, and no absolute paths. CI regenerates it and fails on a difference, so a dependency change cannot
// leave notices stale.
//
// Run: pnpm run notices        (write THIRD_PARTY_NOTICES.md)
//      pnpm run check:notices  (compare, no write)
import { execSync } from "node:child_process";
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const OUT = join(ROOT, "THIRD_PARTY_NOTICES.md");
const LICENSE_FILE = /^(?:licen[cs]e|copying|notice)(?:\..+)?$/i;

function report() {
  const raw = execSync("pnpm licenses list --prod --json", { encoding: "utf8", maxBuffer: 32 * 1024 * 1024 });
  try { return JSON.parse(raw); } catch { throw new Error("pnpm licenses list did not return JSON"); }
}

const textOf = (file) => readFileSync(file, "utf8").replace(/\r\n/g, "\n").trimEnd();

function packageFiles(dir) {
  let entries = [];
  try { entries = readdirSync(dir); } catch { return []; }
  return entries.filter((name) => LICENSE_FILE.test(name)).sort((a, b) => a.localeCompare(b));
}

export function notices() {
  const rows = [];
  for (const [license, entries] of Object.entries(report())) {
    for (const entry of Array.isArray(entries) ? entries : []) {
      const dir = Array.isArray(entry.paths) ? entry.paths[0] : null;
      if (!dir) throw new Error(`no path for ${entry.name}`);
      const files = packageFiles(dir);
      if (!files.length) throw new Error(`no licence file in ${entry.name}@${entry.versions?.join(",")}`);
      const manifest = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
      const repository = typeof manifest.repository === "string" ? manifest.repository
        : manifest.repository && typeof manifest.repository.url === "string" ? manifest.repository.url : null;
      rows.push({
        name: entry.name, versions: Array.isArray(entry.versions) ? entry.versions : [],
        license, repository: repository || manifest.homepage || null,
        files: files.map((name) => ({ name, text: textOf(join(dir, name)) })),
      });
    }
  }
  rows.sort((a, b) => a.name.localeCompare(b.name) || a.versions.join(",").localeCompare(b.versions.join(",")));
  const seen = new Set();
  const unique = rows.filter((row) => {
    const key = `${row.name}@${row.versions.join(",")}`;
    if (seen.has(key)) return false;
    seen.add(key);
    return true;
  });
  const lines = [
    "# Third-party notices",
    "",
    "This file lists the production dependencies of `@ninsei-labs/sdk` and the licence text each package ships.",
    "It is generated from the installed production tree; do not edit it by hand.",
    "",
    `Generated by \`tools/third-party-notices.mjs\`. Licences accepted by the project are listed in`,
    "[LICENSE-POLICY.md](LICENSE-POLICY.md).",
    "",
  ];
  for (const row of unique) {
    lines.push(`## ${row.name}${row.versions.length ? ` ${row.versions.join(", ")}` : ""}`, "");
    lines.push(`License: ${row.license}`);
    if (row.repository) lines.push(`Source: ${row.repository}`);
    lines.push("");
    for (const file of row.files) {
      lines.push(`### ${file.name}`, "", "```text", file.text, "```", "");
    }
  }
  return `${lines.join("\n").replace(/\n{3,}/g, "\n\n").trimEnd()}\n`;
}

const isMain = process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href;
if (isMain) {
  const check = process.argv.includes("--check");
  let expected;
  try { expected = notices(); } catch (error) {
    console.error("third-party notices: " + (error?.message || error));
    process.exit(2);
  }
  if (check) {
    const actual = existsSync(OUT) ? readFileSync(OUT, "utf8").replace(/\r\n/g, "\n") : "";
    if (actual !== expected) {
      console.error("third-party notices: THIRD_PARTY_NOTICES.md is stale; run `pnpm run notices`");
      process.exit(1);
    }
    console.log(`third-party notices: ${expected.split("\n").filter((line) => line.startsWith("## ")).length} package(s), current`);
  } else {
    writeFileSync(OUT, expected, "utf8");
    console.log(`third-party notices: wrote ${OUT}`);
  }
}
